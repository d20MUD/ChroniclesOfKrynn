#!/usr/bin/env python3
"""Generate the compiled read-only schema contract from reviewed migrations."""
from pathlib import Path
import json,re,sys
root=Path(__file__).resolve().parents[1]
text='\n'.join((root/'sql'/name).read_text() for name in ['20261110_clan_progression_v001.sql','20261110_clan_progression_v002.sql'])
lines=['/* Generated by scripts/generate_clan_schema_contract.py; do not hand edit. */',
       'static const struct { const char *table, *fragment; } clan_schema_fragments[] = {']
for match in re.finditer(r'CREATE TABLE IF NOT EXISTS (\w+) \((.*?)\) ENGINE=InnoDB',text,re.S):
 table,body=match.groups()
 # Named constraints, including multiline checks, end at a top-level comma.
 for con in re.finditer(r'CONSTRAINT\s+\w+\s+',body):
  start=con.start();depth=0;quote=False;end=start
  while end<len(body):
   ch=body[end]
   if ch=="'":quote=not quote
   if not quote:
    if ch=='(':depth+=1
    elif ch==')':depth-=1
    elif ch==',' and depth==0:break
   end+=1
  lines.append('  {'+json.dumps(table)+', '+json.dumps(re.sub(r' ON (?:UPDATE|DELETE) RESTRICT', '', body[start:end].strip()))+'},')
 # Index identities and their columns must exist, not just table names.
 for index in re.finditer(r'(?:UNIQUE )?KEY \w+ \([^)]*\)',body):
  lines.append('  {'+json.dumps(table)+', '+json.dumps(index.group())+'},')
for table,body in re.findall(r'CREATE TABLE IF NOT EXISTS (\w+) \((.*?)\) ENGINE=InnoDB',text,re.S):
 for name,rest in re.findall(r'^ +([a-z_]+) ([^\n]+)',body,re.M):
  if 'PRIMARY KEY' in rest:lines.append('  {'+json.dumps(table)+', '+json.dumps('PRIMARY KEY ('+name+')')+'},')
  elif re.search(r'\bUNIQUE\b',rest):lines.append('  {'+json.dumps(table)+', '+json.dumps('UNIQUE KEY '+name+' ('+name+')')+'},')
lines+=['};','static const struct {const char *table, *name, *type; int length; const char *nullable, *default_value;} clan_schema_columns[] = {']
for table,body in re.findall(r'CREATE TABLE IF NOT EXISTS (\w+) \((.*?)\) ENGINE=InnoDB',text,re.S):
 for name,typ,length,rest in re.findall(r'^ +([a-z_]+) (VARCHAR|BIGINT|INT|TINYINT|LONGTEXT|TEXT|TIMESTAMP)(?:\((\d+)\))?([^\n]*)',body,re.M):
  default=re.search(r"\bDEFAULT\s+('(?:''|[^'])*'|[A-Z_()]+|-?\d+)",rest)
  value=default.group(1).strip("'").lower() if default else None
  lines.append('  {'+', '.join([json.dumps(table),json.dumps(name),json.dumps(typ.lower()),length or '0',json.dumps('NO' if 'NOT NULL' in rest else 'YES'),json.dumps(value) if value is not None else 'NULL'])+'},')
lines+=['};','static const struct {const char *table, *name;} clan_schema_foreign_keys[] = {']
for table,body in re.findall(r'CREATE TABLE IF NOT EXISTS (\w+) \((.*?)\) ENGINE=InnoDB',text,re.S):
 for name in re.findall(r'CONSTRAINT (\w+) FOREIGN KEY',body):lines.append('  {'+json.dumps(table)+', '+json.dumps(name)+'},')
lines+=['};','static const struct {const char *name, *event, *table, *body;} clan_schema_triggers[] = {']
for name,event,table,body in re.findall(r'CREATE TRIGGER (\w+) BEFORE (\w+) ON (\w+)\s+FOR EACH ROW\s+(BEGIN.*?END)//',text,re.S):
 lines.append('  {'+', '.join(map(json.dumps,[name,event,table,body]))+'},')
lines+=['};','']
output=root/'src/clan_repository_schema.inc'
generated='\n'.join(lines)
if '--check' in sys.argv:
 if output.read_text()!=generated:raise SystemExit('Clan schema contract is stale; regenerate it from the reviewed SQL migrations')
else:output.write_text(generated)
