int spellhelp_public(int spellnum)
{
  const struct spell_info_type *info;
  if (spellnum <= 0 || spellnum > TOP_SPELL_DEFINE) return 0;
  if (spellnum >= NUM_SPELLS && !is_spellnum_psionic(spellnum)) return 0;
  info = &spell_info[spellnum];
  return info->name && *info->name && info->name[0] != '!' &&
         info->min_position != POS_DEAD && !info->no_player && !info->cant_cast &&
         info->actual_ability;
}

static const char *sh_lookup_name(int spellnum)
{
  return spellhelp_public(spellnum) ? spell_info[spellnum].name : sh_legacy_name(spellnum);
}

static const struct spellhelp_rule *sh_rule(int spellnum)
{
  size_t i;
  for (i = 0; i < sizeof(spellhelp_rules)/sizeof(spellhelp_rules[0]); i++)
    if (spellhelp_rules[i].spell == spellnum) return &spellhelp_rules[i];
  return NULL;
}

/* The protocol encodes @c (cyan) and @n (normal) as tab-prefixed colors. */
static void sh_line(struct sh_text *out, const char *label, const char *description)
{
  if (description && *description)
    sh_append(out, "\tc%s:\tn %s\r\n", label, description);
}

/* Match the damage casting-class switch in fight.c. These settings do not
 * modify healing, save DCs or durations. */
static void sh_server_settings(struct sh_text *out, int spellnum,
                               const struct spellhelp_rule *rule)
{
  const struct spell_info_type *info = &spell_info[spellnum];
  int i, j, damaging, arcane = 0, divine = 0, psionic = 0;
  int damage_rows = 0;
  damaging = rule ? strcmp(rule->damage, "None.") != 0 : IS_SET(info->routines, MAG_DAMAGE);
  /* These delayed/environmental/ability paths do not preserve the original casting-class bonus. */
  if (spellnum == SPELL_ACID_FOG || spellnum == SPELL_ACID_ARROW ||
      spellnum == SPELL_CLOUDKILL || spellnum == SPELL_INCENDIARY_CLOUD ||
      spellnum == SPELL_IMPLODE || spellnum == SPELL_STORM_OF_VENGEANCE ||
      spellnum == SPELL_SPIKE_GROWTH || spellnum == SPELL_SPIKE_STONES ||
      spellnum == SPELL_WALL_OF_FIRE || spellnum == SPELL_WALL_OF_THORNS ||
      spellnum == SPELL_GENERIC_AOE || spellnum == SPELL_BLADE_BARRIER ||
      spellnum == SPELL_AQUEOUS_ORB || spellnum == SPELL_CAUSTIC_BLOOD ||
      spellnum == SPELL_BLACK_TENTACLES || spellnum == SPELL_GREATER_BLACK_TENTACLES ||
      spellnum == SPELL_HOSTILE_JUXTAPOSITION ||
      spellnum == PSIONIC_CONCUSSIVE_ONSLAUGHT || spellnum == PSIONIC_ENERGY_RETORT ||
      spellnum == PSIONIC_EMPATHIC_FEEDBACK || spellnum == PSIONIC_ENERGY_CONVERSION ||
      spellnum == SPELL_HEDGING_WEAPONS || spellnum == SPELL_SUN_METAL || spellnum == SPELL_DANCING_WEAPON || spellnum == SPELL_SPIRITUAL_WEAPON || spellnum == SPELL_HOLY_JAVELIN || spellnum == SPELL_MOONBEAM ||
      spellnum == SPELL_FIRE_SHIELD ||
      spellnum == SPELL_COLD_SHIELD || spellnum == SPELL_ACID_SHEATH ||
      IS_SET(info->routines, MAG_SUMMONS)) damaging = 0;
  psionic = is_spellnum_psionic(spellnum);
  if (!psionic)
  {
    for (i = 0; i < NUM_CLASSES; i++)
    {
      if (info->min_level[i] <= 0 || info->min_level[i] >= LVL_IMMORT) continue;
      switch (i)
      {
      case CLASS_WIZARD: case CLASS_SORCERER: case CLASS_BARD:
        arcane = 1;
        break;
      case CLASS_CLERIC: case CLASS_DRUID: case CLASS_PALADIN: case CLASS_RANGER:
        divine = 1;
        break;
      default:
        break;
      }
    }
    /* Domain access is divine even without a normal cleric assignment. */
    for (i = 0; i < NUM_DOMAINS; i++)
      for (j = 0; j < MAX_DOMAIN_SPELLS; j++)
        if (domain_list[i].domain_spells[j] == spellnum)
          divine = 1;
  }
  if (damaging)
  {
    if (psionic && CONFIG_PSIONIC_DAMAGE != 0)
      sh_append(out, "\tcGlobal damage bonus:\tn Psionic %+d%% (%d%% of normal damage).\r\n",
                CONFIG_PSIONIC_DAMAGE, 100 + CONFIG_PSIONIC_DAMAGE);
    if (arcane && CONFIG_ARCANE_DAMAGE != 0)
      sh_append(out, "\tcGlobal damage bonus:\tn Wizard/Sorcerer/Bard %+d%% (%d%% of normal damage).\r\n",
                CONFIG_ARCANE_DAMAGE, 100 + CONFIG_ARCANE_DAMAGE);
    if (divine && CONFIG_DIVINE_DAMAGE != 0)
      sh_append(out, "\tcGlobal damage bonus:\tn Cleric/Druid/Paladin/Ranger %+d%% (%d%% of normal damage).\r\n",
                CONFIG_DIVINE_DAMAGE, 100 + CONFIG_DIVINE_DAMAGE);
    damage_rows = (psionic && CONFIG_PSIONIC_DAMAGE != 0) ||
                  (arcane && CONFIG_ARCANE_DAMAGE != 0) ||
                  (divine && CONFIG_DIVINE_DAMAGE != 0);
  }
  if (damage_rows && IS_SET(info->routines, MAG_LOOPS))
    sh_line(out, "Repeated hits", "The current combat rules consume the casting-class bonus after the first damage event; later hits do not automatically receive it.");
  if (spellnum == SPELL_ACID_FOG &&
      ((arcane && CONFIG_ARCANE_DAMAGE) || (divine && CONFIG_DIVINE_DAMAGE)))
    sh_line(out, "Periodic damage", "Acid Fog uses the affected creature as its damage source; the original caster's global damage bonus is not preserved.");
  if (spellnum == SPELL_SHIELD || spellnum == PSIONIC_MENTAL_BARRIER || spellnum == SPELL_INVISIBLE ||
      spellnum == SPELL_MAGE_ARMOR || spellnum == SPELL_EPIC_MAGE_ARMOR ||
      spellnum == SPELL_GREATER_INVIS || spellnum == SPELL_INVISIBILITY_SPHERE ||
      spellnum == SPELL_SHADOW_SHIELD || spellnum == SPELL_STRENGTHEN_BONE ||
      spellnum == SPELL_BARKSKIN || spellnum == SPELL_SHIELD_OF_FAITH ||
      spellnum == SPELL_GROUP_SHIELD_OF_FAITH ||
      spellnum == ALC_DISC_AFFECT_PSYCHOKINETIC || spellnum == SPELL_INCORPOREAL_FORM ||
      spellnum == SPELL_HEDGING_WEAPONS || spellnum == SPELL_STUNNING_BARRIER || spellnum == SPELL_VEIL_OF_POSITIVE_ENERGY || spellnum == SPELL_LITANY_OF_DEFENSE || spellnum == SPELL_MAGIC_VESTMENT || spellnum == SPELL_GIRD_ALLIES ||
      spellnum == SPELL_WARDING_WEAPON || spellnum == SPELL_PLANAR_SOUL ||
      spellnum == SPELL_LESSER_EVOLUTION_SURGE || spellnum == SPELL_HOLY_AURA ||
      spellnum == PSIONIC_FORCE_SCREEN || spellnum == PSIONIC_INERTIAL_ARMOR || spellnum == PSIONIC_DEFENSIVE_PRECOGNITION || spellnum == PSIONIC_OAK_BODY || spellnum == PSIONIC_EPIC_PSIONIC_WARD)
    sh_append(out, "\tcArmor class limit:\tn Normal total AC is capped at %d; this does not change the spell's listed bonus.\r\n", CONFIG_PLAYER_AC_CAP);
}

/* Fixed visible columns; color escapes do not count toward label width. */
#define SH_LABEL_WIDTH 20
#define SH_TEXT_COLUMN (SH_LABEL_WIDTH + 2)
#define SH_LINE_WIDTH 80
static char *sh_align(struct sh_text *raw)
{
  struct sh_text out = {NULL, 0, 0, 0};
  const char *line, *end, *body, *label_end, *next;
  char label[SH_LABEL_WIDTH + 1];
  size_t length, take, split;
  for (line = raw->data; line && *line; line = next)
  {
    end = strchr(line, '\r');
    if (!end) end = line + strlen(line);
    next = *end ? end + 1 : end;
    if (*next == '\n') next++;
    body = line;
    label_end = NULL;
    if (!strncmp(line, "\tc", 2)) label_end = strstr(line + 2, ":\tn ");
    if (label_end && label_end < end && (size_t)(label_end - line - 2) <= SH_LABEL_WIDTH)
    {
      length = label_end - line - 2;
      memcpy(label, line + 2, length); label[length] = '\0';
      sh_append(&out, "\tc%-*s:\tn ", SH_LABEL_WIDTH, label);
      body = label_end + 4;
    }
    else sh_append(&out, "%*s", SH_TEXT_COLUMN, "");
    while (body < end && isspace((unsigned char)*body)) body++;
    while (body < end)
    {
      length = end - body;
      take = length < SH_LINE_WIDTH - SH_TEXT_COLUMN ? length : SH_LINE_WIDTH - SH_TEXT_COLUMN;
      if (take < length)
      {
        for (split = take; split > 0 && !isspace((unsigned char)body[split]); split--) ;
        if (split) take = split;
      }
      sh_append(&out, "%.*s", (int)take, body);
      body += take;
      while (body < end && isspace((unsigned char)*body)) body++;
      if (body < end) sh_append(&out, "\r\n%*s", SH_TEXT_COLUMN, "");
    }
    sh_append(&out, "\r\n");
  }
  free(raw->data);
  if (out.failed) { free(out.data); return NULL; }
  return out.data;
}

char *spellhelp_render(int spellnum)
{
  struct sh_text out = {NULL, 0, 0, 0};
  const struct spell_info_type *info;
  const struct spellhelp_rule *rule;
  int i, j, found, psionic, targets;
  static const char *disciplines[] = {"unspecified", "Clairsentience", "Metacreativity",
    "Psychokinesis", "Psychometabolism", "Psychoportation", "Telepathy"};
  static const struct sh_flag target_names[] = {
    {TAR_CHAR_ROOM,"character in the room"}, {TAR_CHAR_WORLD,"character anywhere"},
    {TAR_FIGHT_SELF,"self in combat"}, {TAR_FIGHT_VICT,"combat opponent"},
    {TAR_SELF_ONLY,"self"}, {TAR_NOT_SELF,"others only"}, {TAR_OBJ_INV,"carried object"},
    {TAR_OBJ_ROOM,"object in the room"}, {TAR_OBJ_WORLD,"object anywhere"}, {TAR_OBJ_EQUIP,"equipped object"}};

  if (!spellhelp_public(spellnum))
  {
    const char *legacy = sh_legacy_name(spellnum);
    rule = sh_rule(spellnum);
    if (!legacy || !rule) return NULL;
    sh_line(&out, is_spellnum_psionic(spellnum) ? "Power" : "Spell", legacy);
    sh_line(&out, "Status", (spellnum == SPELL_ABSOLUTE_GEAS ||
      spellnum == SPELL_HIVE_COMMANDER_MARK || spellnum == PSIONIC_GRAVITY_WELL) ?
      "Unavailable: perk effect or command, not a separately manifestable power." :
      is_spellnum_psionic(spellnum) ?
      "Unavailable: unregistered power ID; no active manifestation registration." :
      (spellnum == SPELL_MINOR_RAPID_BUFF ||
      spellnum == SPELL_RAPID_BUFF || spellnum == SPELL_GREATER_RAPID_BUFF) ?
      "Unavailable: normal player casting explicitly disabled." :
      (spellnum == SPELL_PALANTHAS_RECALL || spellnum == SPELL_SANCTION_RECALL ||
      spellnum == SPELL_SOLACE_RECALL || spellnum == SPELL_SILVERYMOON_RECALL || spellnum == SPELL_TRIBOAR_RECALL || spellnum == SPELL_LUSKAN_RECALL || spellnum == SPELL_MIRABAR_RECALL) ?
      "Unavailable: campaign-specific recall; normal player casting disabled." :
      spellnum == SPELL_PLANE_SHIFT ?
      "Unavailable: not registered for this campaign." :
      (spellnum == SPELL_REINCARNATE || spellnum == SPELL_BALEFUL_POLYMORPH ||
       spellnum == SPELL_GREATER_SCRYING || spellnum == SPELL_SHAPECHANGE ||
       spellnum == SPELL_EMBALM || spellnum == SPELL_ELEMENTAL_RESISTANCE ||
       spellnum == SPELL_PRESERVE || spellnum == SPELL_MINOR_CREATE ||
       (spellnum >= SPELL_DEATH_SHIELD && spellnum <= SPELL_AIR_WALKER)) ?
      "Unavailable: unfinished ID, not registered for casting." :
      (spellnum == SPELL_FIRE_BREATHE || spellnum == SPELL_DEATHCLOUD || spellnum == SPELL_INCENDIARY || spellnum == SPELL_FROST_BREATHE ||
       spellnum == SPELL_LIGHTNING_BREATHE || spellnum == SPELL_BLADES ||
       spellnum == SPELL_I_DARKNESS || spellnum == SPELL_ESHIELD_DAM ||
       spellnum == SPELL_ACID_BREATHE || spellnum == SPELL_POISON_BREATHE ||
       spellnum == SPELL_GAS_BREATHE || spellnum == SPELL_AURAK_DEATH_THROES || (spellnum >= SPELL_FSHIELD_DAM && spellnum <= SPELL_ASHIELD_DAM)) ?
      "Unavailable: internal creature ability or automatic effect, not a player spell." :
      "Unavailable: legacy ID, not registered for casting.");
    sh_line(&out, "Description", rule->effect);
    if (strcmp(rule->damage, "None."))
    {
      sh_line(&out, "Damage", rule->damage);
      sh_line(&out, "Saves", rule->saves);
    }
    sh_line(&out, "Duration", rule->duration);
    sh_line(&out, "Notes", rule->restrictions);
    if (out.failed) { free(out.data); return NULL; }
    return sh_align(&out);
  }
  info = &spell_info[spellnum];
  rule = sh_rule(spellnum);
  psionic = is_spellnum_psionic(spellnum);
  sh_line(&out, psionic ? "Power" : "Spell", info->name);
  if (psionic)
  {
    int discipline = psionic_powers[spellnum].power_type;
    sh_line(&out, "School", discipline >= 0 && discipline < NUM_PSIONIC_POWER_TYPES ? disciplines[discipline] : "unspecified");
  }
  else sh_line(&out, "School", info->schoolOfMagic >= 0 && info->schoolOfMagic < NUM_SCHOOLS ? spell_schools[info->schoolOfMagic] : "unspecified");

  sh_append(&out, "\tcClasses:\tn ");
  found = 0;
  for (i = 0; i < NUM_CLASSES; i++)
    if (info->min_level[i] > 0 && info->min_level[i] < LVL_IMMORT)
    {
      sh_append(&out, "%s%s level %d (circle %d)", found ? "; " : "", class_names[i], info->min_level[i], get_spell_circle(spellnum, i));
      found = 1;
    }
  if (!found) sh_append(&out, "No standard class assignment");
  sh_append(&out, "\r\n");
  found = 0;
  for (i = 0; i < NUM_DOMAINS; i++)
    for (j = 0; j < MAX_DOMAIN_SPELLS; j++)
      if (domain_list[i].domain_spells[j] == spellnum)
      {
        if (!found) sh_append(&out, "\tcDomains:\tn ");
        sh_append(&out, "%s%s (circle %d)", found ? "; " : "", domain_list[i].name, j + 1);
        found = 1;
      }
  if (found) sh_append(&out, "\r\n");

  targets = info->targets & ~TAR_IGNORE;
  if (IS_SET(targets, TAR_SELF_ONLY)) targets = TAR_SELF_ONLY;
  if (!targets)
  {
    if (IS_SET(info->routines, MAG_GROUPS)) sh_line(&out, "Targets", "Group members in the room");
    else if (IS_SET(info->routines, MAG_AREAS | MAG_MASSES)) sh_line(&out, "Targets", "Eligible creatures in the room");
    else if (IS_SET(info->routines, MAG_ROOM)) sh_line(&out, "Targets", "The room");
    else sh_line(&out, "Targets", "No named target");
  }
  else SH_FLAGS(&out, "Targets", targets, target_names);
  if (targets && IS_SET(info->routines, MAG_GROUPS))
    sh_line(&out, "Recipients", "Group members in the room");
  if (targets && IS_SET(info->routines, MAG_AREAS | MAG_MASSES))
    sh_line(&out, "Area", "Also affects eligible creatures in the room");
  if (info->touch_spell) sh_line(&out, "Touch", "Requires a successful touch attack");

  if (psionic && psionic_powers[spellnum].can_augment)
  {
    if (rule && rule->augmentation) sh_line(&out, "Augmentation", rule->augmentation);
    else sh_line(&out, "Augmentation", "Effect details are not yet documented.");
    sh_append(&out, "Additional PSP are spent in steps of %d, up to %d, subject to your manifester limit.\r\n",
      psionic_powers[spellnum].augment_amount, psionic_powers[spellnum].max_augment);
  }
  if (rule)
  {
    sh_line(&out, "Description", rule->effect);
    sh_line(&out, "Damage", rule->damage);
    sh_line(&out, "Saves", rule->saves);
    sh_line(&out, "Duration", rule->duration);
    sh_line(&out, "Notes", rule->restrictions);
  }
  else sh_line(&out, "Description", "Detailed effects are not yet documented.");
  sh_server_settings(&out, spellnum, rule);
  if (out.failed) { free(out.data); return NULL; }
  return sh_align(&out);
}

/* Keep help and spellhelp name handling identical. */
static void sh_normalize_name(const char *argument, char *name, size_t size)
{
  size_t length;
  while (*argument && isspace((unsigned char)*argument)) argument++;
  snprintf(name, size, "%s", argument);
  length = strlen(name);
  while (length && isspace((unsigned char)name[length - 1])) name[--length] = '\0';
  if (length >= 2 && ((name[0] == '\'' && name[length-1] == '\'') ||
                     (name[0] == '"' && name[length-1] == '"')))
  { memmove(name, name + 1, length - 2); name[length - 2] = '\0'; }
}

ACMD(do_spellhelp)
{
  int i, match = 0, matches = 0, total = 0, reviewed = 0, legacy = 0;
  char name[MAX_INPUT_LENGTH];
  char *text;
  struct sh_text choices = {NULL, 0, 0, 0};
  sh_normalize_name(argument, name, sizeof(name));
  if (!*name)
  {
    send_to_char(ch, "\tcUsage:\tn spellhelp <spell or power name>\r\n"
      "       spellhelp coverage\r\nExact names and unambiguous prefixes are accepted; quotes are optional.\r\n");
    return;
  }
  if (!strcasecmp(name, "coverage"))
  {
    for (i = 1; i <= TOP_SPELL_DEFINE; i++)
    {
      if (spellhelp_public(i)) { total++; if (sh_rule(i)) reviewed++; }
      else if (sh_legacy_name(i) && sh_rule(i)) legacy++;
    }
    send_to_char(ch, "\tcCoverage:\tn %d public spells/powers; %d core-mechanics entries;\r\n"
      "%d registration-only entries; %d unavailable entries documented.\r\n"
      "Full interaction audits remain pending.\r\n", total, reviewed, total-reviewed, legacy);
    return;
  }
  /* Exact names take precedence over all prefix matches. */
  for (i = 1; i <= TOP_SPELL_DEFINE; i++)
    if (sh_lookup_name(i) && !strcasecmp(name, sh_lookup_name(i))) { match = i; break; }
  if (!match)
  {
    sh_append(&choices, "\tcMatches:\tn Please choose a more specific name:\r\n");
    for (i = 1; i <= TOP_SPELL_DEFINE; i++)
      if (sh_lookup_name(i) && !strncasecmp(name, sh_lookup_name(i), strlen(name)))
      {
        match = i; matches++;
        sh_append(&choices, "  %s\r\n", sh_lookup_name(i));
      }
    if (matches > 1)
    {
      if (!choices.failed && ch->desc) page_string(ch->desc, choices.data, TRUE);
      else send_to_char(ch, "Multiple matches; please enter a full name.\r\n");
      free(choices.data);
      return;
    }
    free(choices.data);
  }
  if (!match) { send_to_char(ch, "No public spell or psionic power matches '%s'.\r\n", name); return; }
  text = spellhelp_render(match);
  if (!text) { send_to_char(ch, "Unable to generate spell help.\r\n"); return; }
  if (ch->desc) page_string(ch->desc, text, TRUE);
  else send_to_char(ch, "%s", text);
  free(text);
}

/* Ambiguous prefixes fall through to ordinary help rather than stealing topics. */
int spellhelp_try_show(struct char_data *ch, const char *argument)
{
  char name[MAX_INPUT_LENGTH];
  int i, matches = 0;
  sh_normalize_name(argument, name, sizeof(name));
  if (!*name) return 0;
  for (i = 1; i <= TOP_SPELL_DEFINE; i++)
  {
    const char *candidate = sh_lookup_name(i);
    if (!candidate) continue;
    if (!strcasecmp(name, candidate))
    {
      do_spellhelp(ch, argument, 0, 0);
      return 1;
    }
    if (!strncasecmp(name, candidate, strlen(name))) matches++;
  }
  if (matches != 1) return 0;
  do_spellhelp(ch, argument, 0, 0);
  return 1;
}

